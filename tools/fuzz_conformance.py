GENERATORS = {
    "layout": layout_case,
    "table": table_case,
    "text": text_case,
    "paint": paint_case,
    "inline": inline_case,
    "cascade": cascade_case,
    "parser": parser_case,
    "image": image_case,
}


def generate_case(seed, index, families=FAMILIES):
    family = families[index % len(families)]
    # Each index owns its RNG stream, so --start and sharded campaigns replay.
    digest = hashlib.sha256(f"{seed}:{index}:{family}".encode()).digest()
    rng = random.Random(int.from_bytes(digest[:16], "big"))
    source, features = GENERATORS[family](rng)
    return GeneratedCase(index, seed, family, source, tuple(features))


def geometry(ours, reference, dom_match):
    differences, compared = [], 0
    if dom_match:
        for i, (node, box) in enumerate(zip(ours["document"]["nodes"], ours["scene"]["boxes"])):
            if not node["tag"] or box is None:
                continue
            expected = reference["nodes"][i].get("rect")
            if expected is None:
                continue
            compared += 1
            delta = {key: box["border"][key] - round(expected[key] * 60) for key in ("x", "y", "w", "h")}
            if any(delta.values()):
                differences.append({"node": i, "tag": node["tag"], "delta_app_units": delta})
    return compared, differences


def failure_kind(row):
    if row.get("oracle_error"):
        return "oracle-error"
    if row.get("timed_out"):
        return "timeout"
    if row.get("exit_code") != 0:
        return "crash"
    if not row.get("dom_match"):
        return "dom"
    if not row.get("geometry_match"):
        return "geometry"
    if row.get("different_pixels"):
        return "pixels"
    return "pass"


def failure_signature(row):
    kind = failure_kind(row)
    family = row.get("family", "unknown")
    if kind == "geometry":
        # Root heights are usually only a downstream symptom.  Bucket on the
        # first content box when possible so separate layout bugs do not all
        # collapse into geometry:<family>:html:h.
        first = next(
            (difference for difference in row["box_differences"] if difference["tag"] not in ("html", "body")),
            row["box_differences"][0],
        )
        components = "".join(k for k, v in first["delta_app_units"].items() if v)
        return f"geometry:{family}:{first['tag']}:{components}"
    if kind == "dom":
        return f"dom:{family}"
    if kind == "crash":
        stderr = row.get("stderr", "").splitlines()
        tail = stderr[-1][:120] if stderr else "no-stderr"
        return f"crash:{family}:{tail}"
    if kind == "timeout":
        return f"timeout:{family}"
    if kind == "oracle-error":
        return f"oracle-error:{family}"
    if kind == "pixels":
        maximum = row.get("max_difference", 0)
        delta = "one" if maximum <= 1 else "small" if maximum <= 15 else "large"
        count = row.get("different_pixels", 0)
        extent = "few" if count <= 32 else "some" if count <= 512 else "many"
        return f"pixels:{family}:{delta}:{extent}"
    return "pass"


class Campaign:
    def __init__(self, args, out):
        self.args = args
        self.out = out
        self.oracle = Gecko(args.firefox, args.geckodriver, out)
        self.binary = pathlib.Path(args.binary).resolve()

    def close(self):
        self.oracle.close()

    def run(self, case, stem=None):
        stem = stem or case.name
        source_path = self.out / f"{stem}.html"
        source_path.write_bytes(case.source)
        source_hash = hashlib.sha256(case.source).hexdigest()
        gecko = self.out / f"{stem}-gecko"
        lizard_png = self.out / f"{stem}-lizard.png"
        lizard_json = self.out / f"{stem}-lizard.json"
        row = {
            "name": stem,
            "index": case.index,
            "seed": case.seed,
            "family": case.family,
            "features": list(case.features),
            "source_sha256": source_hash,
        }
        try:
            self.oracle.capture(source_path, self.args.width, self.args.height, gecko)
        except Exception as error:  # Preserve a malformed-source oracle failure.
            row.update(exit_code=None, oracle_error=repr(error), strict_pass=False, policy_pass=False)
            row["failure_kind"] = failure_kind(row)
            row["signature"] = failure_signature(row)
            return row
        reference = json.loads(gecko.with_suffix(".json").read_text())
        if reference["source_sha256"] != source_hash:
            raise RuntimeError(f"stale Gecko source for {stem}")
        try:
            run = subprocess.run(
                [str(self.binary), "render", str(source_path), str(lizard_png), str(self.args.width), str(self.args.height), str(lizard_json)],
                capture_output=True,
                text=True,
                timeout=self.args.timeout,
            )
        except subprocess.TimeoutExpired as error:
            stderr = error.stderr or ""
            if isinstance(stderr, bytes):
                stderr = stderr.decode("utf-8", "replace")
            row.update(exit_code=None, stderr=stderr[-4000:], timed_out=True)
            row.update(strict_pass=False, policy_pass=False, accepted_with_image_tolerance=False)
            row["failure_kind"] = failure_kind(row)
            row["signature"] = failure_signature(row)
            return row
        row.update(exit_code=run.returncode, stderr=run.stderr[-4000:])
        if run.returncode == 0:
            metrics, diff = compare(lizard_png, gecko.with_suffix(".png"))
            row.update(metrics)
            if diff is not None and not metrics["passed"]:
                diff.save(self.out / f"{stem}-diff.png")
            ours = json.loads(lizard_json.read_text())
            row["dom_match"] = [canon(n) for n in ours["document"]["nodes"]] == [canon(n) for n in reference["nodes"]]
            compared, differences = geometry(ours, reference, row["dom_match"])
            row.update(
                box_probes_compared=compared,
                box_differences=differences,
                geometry_match=row["dom_match"] and not differences,
            )
            row.update(acceptance(metrics, row["dom_match"], row["geometry_match"]))
        else:
            row.update(strict_pass=False, policy_pass=False, accepted_with_image_tolerance=False)
        row["failure_kind"] = failure_kind(row)
        row["signature"] = failure_signature(row)
        if row["failure_kind"] == "pass" and not self.args.keep_passes:
            for path in (
                source_path,
                gecko.with_suffix(".png"),
                gecko.with_suffix(".json"),
                lizard_png,
                lizard_json,
                self.out / f"{stem}-diff.png",
            ):
                path.unlink(missing_ok=True)
        return row


DECLARATION = re.compile(rb"(?P<lead>[{;])(?P<space>\s*)(?P<decl>[-a-z]+\s*:[^;{}\"']+;?)", re.I)


def declaration_reductions(source):
    """Yield byte-exact candidates with one CSS declaration removed."""
    matches = list(DECLARATION.finditer(source))
    for match in reversed(matches):
        # Keep reset declarations: removing them mostly rediscovers browser defaults.
        declaration = match.group("decl").lower()
        if declaration.startswith((b"margin:0", b"padding:0", b"background:white", b"font:")):
            continue
        start, end = match.span("decl")
        yield source[:start] + source[end:]


def minimize(case, runner, wanted_signature, stem):
    current = case
    attempts = 0
    changed = True
    while changed and attempts < runner.args.minimize_attempts:
        changed = False
        for candidate_source in declaration_reductions(current.source):
            if attempts >= runner.args.minimize_attempts:
                break
            attempts += 1
            candidate = dataclasses.replace(current, source=candidate_source)
            row = runner.run(candidate, stem=f"{stem}-try")
            if row["signature"] == wanted_signature:
                current = candidate
                changed = True
                break
    final_row = runner.run(current, stem=stem)
    for path in runner.out.glob(f"{stem}-try*"):
        path.unlink(missing_ok=True)
    return current, final_row, attempts


def output_directory(value):
    path = pathlib.Path(value)
    return path if path.is_absolute() else ROOT / path


def make_report(args, rows, minimized, out):
    buckets = {}
    for row in rows:
        buckets.setdefault(row["signature"], []).append(row["name"])
    result = {
        "cases": len(rows),
        "exact_passes": sum(row["failure_kind"] == "pass" for row in rows),
        "failures": sum(row["failure_kind"] != "pass" for row in rows),
        "failure_kinds": {
            kind: sum(row["failure_kind"] == kind for row in rows)
            for kind in ("crash", "timeout", "dom", "geometry", "pixels", "oracle-error")
        },
        "buckets": [{"signature": key, "count": len(value), "representative": value[0]} for key, value in sorted(buckets.items()) if key != "pass"],
        "minimized": minimized,
        "results": rows,
        "environment": {
            "utc": datetime.datetime.now(datetime.timezone.utc).isoformat(),
            "platform": platform.platform(),
            "seed": args.seed,
            "start": args.start,
            "requested_cases": args.cases,
            "families": list(args.families),
            "viewport": [args.width, args.height],
            "lizard_binary_sha256": hashlib.sha256(pathlib.Path(args.binary).read_bytes()).hexdigest(),
            "runner_sha256": hashlib.sha256(pathlib.Path(__file__).read_bytes()).hexdigest(),
            "oracle_code_sha256": ORACLE_CODE_SHA256,
            "font_freetype_fingerprint": ORACLE_ENVIRONMENT,
        },
    }
    (out / "findings.json").write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n")
    cells = []
    for bucket in result["buckets"]:
        name = bucket["representative"]
        cells.append(
            "<tr><td>" + html.escape(bucket["signature"]) + "</td><td>" + str(bucket["count"])
            + "</td><td><a href=\"" + name + ".html\">" + name + "</a></td>"
            + "<td><a href=\"" + name + "-gecko.png\">Gecko</a> "
            + "<a href=\"" + name + "-lizard.png\">Lizard</a> "
            + "<a href=\"" + name + "-diff.png\">Diff</a></td></tr>"
        )
    summary = f"{result['exact_passes']} / {result['cases']} exact; {result['failures']} failures."
    (out / "report.html").write_text(
        '<!doctype html><meta charset="utf-8"><title>Lizard differential fuzzing</title>'
        '<style>body{font:16px/1.5 system-ui;margin:35px}table{border-collapse:collapse}'
        'td,th{padding:8px 14px;border:1px solid #ddd}th{background:#e8eef4}</style>'
        "<h1>Lizard / Gecko email-subset fuzzing</h1><p>" + html.escape(summary) + "</p>"
        "<table><tr><th>Signature</th><th>Count</th><th>Representative</th><th>Images</th></tr>"
        + "".join(cells) + "</table>"
    )
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", required=True)
    parser.add_argument("--firefox", required=True)
    parser.add_argument("--geckodriver", required=True)
    parser.add_argument("--output", default="results/conformance-fuzz")
    parser.add_argument("--seed", type=lambda value: int(value, 0), default=0x4C495A41)
    parser.add_argument("--start", type=int, default=0)
    parser.add_argument("--cases", type=int, default=256)
    parser.add_argument("--families", nargs="+", choices=FAMILIES, default=list(FAMILIES))
    parser.add_argument("--width", type=int, default=360)
    parser.add_argument("--height", type=int, default=260)
    parser.add_argument("--timeout", type=int, default=15)
    parser.add_argument("--keep-passes", action="store_true")
    parser.add_argument("--minimize", type=int, default=8, help="Minimize this many non-pixel failure buckets")
    parser.add_argument("--minimize-attempts", type=int, default=40)
    args = parser.parse_args()
    if args.cases < 1 or args.start < 0 or args.width < 1 or args.height < 1:
        parser.error("cases and viewport dimensions must be positive; start must be nonnegative")
    out = output_directory(args.output)
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    rows = []
    representatives = {}
    runner = Campaign(args, out)
    try:
        for offset in range(args.cases):
            case = generate_case(args.seed, args.start + offset, tuple(args.families))
            row = runner.run(case)
            rows.append(row)
            if row["failure_kind"] not in ("pass", "pixels", "oracle-error"):
                representatives.setdefault(row["signature"], (case, row))
            label = "EXACT" if row["failure_kind"] == "pass" else row["failure_kind"].upper()
            print(f"{offset + 1:04d}/{args.cases:04d} {case.name} {label}", flush=True)
        minimized = []
        for ordinal, (signature, (case, row)) in enumerate(list(representatives.items())[: args.minimize], 1):
            stem = f"minimized-{ordinal:03d}-{case.family}"
            reduced, final_row, attempts = minimize(case, runner, signature, stem)
            minimized.append(
                {
                    "source": stem + ".html",
                    "original": case.name,
                    "original_signature": signature,
                    "failure_kind": final_row["failure_kind"],
                    "signature": final_row["signature"],
                    "attempts": attempts,
                    "bytes_before": len(case.source),
                    "bytes_after": len(reduced.source),
                }
            )
            print(f"minimized {case.name} -> {stem} ({len(case.source)} -> {len(reduced.source)} bytes)", flush=True)
    finally:
        runner.close()
    result = make_report(args, rows, minimized, out)
    print(json.dumps({key: value for key, value in result.items() if key not in ("results", "buckets")}, ensure_ascii=False))
    return 0 if result["failures"] == 0 else 1


