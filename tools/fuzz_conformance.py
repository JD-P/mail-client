@dataclasses.dataclass(frozen=True)
class GeneratedCase:
    index: int
    seed: int
    family: str
    source: bytes
    features: tuple[str, ...]

    @property
    def name(self):
        return f"fuzz-{self.seed:08x}-{self.index:05d}-{self.family}"


def choice(rng, values):
    return values[rng.randrange(len(values))]


def document(style, body):
    return (
        '<!doctype html><meta charset="utf-8"><style>'
        + RESET
        + style
        + "</style>"
        + body
    ).encode("utf-8")


